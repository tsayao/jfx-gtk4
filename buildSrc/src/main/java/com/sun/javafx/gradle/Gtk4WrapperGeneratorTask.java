    @TaskAction
    public void generate() throws Exception {
        classRegistry.clear();
        nsTypePrefix.clear();
        enumCTypes.clear();
        nsSymbolPrefix.clear();
        aliasTargets.clear();
        compounds.clear();
        callbacks.clear();

        DocumentBuilderFactory factory = DocumentBuilderFactory.newInstance();
        factory.setNamespaceAware(false);
        factory.setValidating(false);
        factory.setFeature("http://apache.org/xml/features/nonvalidating/load-external-dtd", false);
        DocumentBuilder builder = factory.newDocumentBuilder();
        builder.setErrorHandler(null);

        List<Element> parsedRoots = new ArrayList<>();
        for (File f : girFiles) {
            if (f.exists()) {
                Document doc = builder.parse(f);
                Element root = doc.getDocumentElement();
                parsedRoots.add(root);
                for (Element ns : childElements(root, "namespace")) {
                    registerNamespaceAndClassStubs(ns);
                }
            } else {
                getLogger().warn("GIR file not found, skipping: " + f);
            }
        }

        resolveHierarchy();
        resolveStructLayouts();

        Set<String> targetKeys = resolveTargetCTypes();
        generatedTypes.clear();
        generatedTypes.addAll(targetKeys);

        for (Element root : parsedRoots) {
            for (Element ns : childElements(root, "namespace")) {
                String nsName = attr(ns, "name");
                for (Element klass : childElements(ns, "class")) {
                    parseClassMethods(klass, nsName, targetKeys);
                }
                for (Element rec : childElements(ns, "record")) {
                    parseClassMethods(rec, nsName, targetKeys);
                }
                for (Element iface : childElements(ns, "interface")) {
                    parseClassMethods(iface, nsName, targetKeys);
                }
                String nsKey = NS_KEY_PREFIX + nsName;
                if (classRegistry.containsKey(nsKey)) {
                    ClassDef nsDef = classRegistry.get(nsKey);
                    for (Element func : childElements(ns, "function")) {
                        MethodDef m = parseMethodNode(func, nsName, null, false, targetKeys);
                        if (m != null) {
                            m.isStatic = true;
                            nsDef.methods.add(m);
                        }
                    }
                    for (Element constNode : childElements(ns, "constant")) {
                        if ("1".equals(attr(constNode, "deprecated"))) continue;
                        String cName = attr(constNode, "name");
                        String cValue = attr(constNode, "value");
                        if (cName.isEmpty()) continue;
                        List<Element> typeNodes = childElements(constNode, "type");
                        if (typeNodes.isEmpty()) continue;
                        String typeName = attr(typeNodes.get(0), "name");
                        String jType = PRIMITIVE_TYPE_MAP.get(typeName);
                        if (jType == null || jType.equals("void") || jType.equals("MemorySegment") || jType.equals("boolean")) continue;
                        String literal = toJavaLiteral(jType, cValue);
                        if (literal == null) continue;
                        ConstDef cd = new ConstDef();
                        cd.name = cName;
                        cd.value = literal;
                        cd.type = jType;
                        nsDef.constants.add(cd);
                    }
                    String cSymPfx = nsSymbolPrefix.getOrDefault(nsName, nsName.toUpperCase() + "_");
                    for (String tag : Arrays.asList("enumeration", "bitfield")) {
                        for (Element enumNode : childElements(ns, tag)) {
                            if ("1".equals(attr(enumNode, "deprecated"))) continue;
                            for (Element member : childElements(enumNode, "member")) {
                                if ("1".equals(attr(member, "deprecated"))) continue;
                                String memberId = attr(member, "c:identifier");
                                String memberVal = attr(member, "value");
                                if (memberId.isEmpty()) continue;
                                try {
                                    Integer.parseInt(memberVal);
                                } catch (NumberFormatException e) {
                                    continue;
                                }
                                String constName = memberId.startsWith(cSymPfx) ? memberId.substring(cSymPfx.length()) : memberId;
                                ConstDef cd = new ConstDef();
                                cd.name = constName;
                                cd.value = memberVal;
                                cd.type = "int";
                                nsDef.constants.add(cd);
                            }
                        }
                    }
                }
            }
        }

        if (targetKeys.isEmpty()) {
            getLogger().warn("No classes to generate. Set includeClasses or includeNamespaceFunctions.");
            return;
        }

        String packagePath = packageName.replace('.', File.separatorChar);
        File packageDir = new File(outputDir, packagePath);
        packageDir.mkdirs();

        for (String key : targetKeys) {
            ClassDef classDef = classRegistry.get(key);
            if (classDef == null) {
                getLogger().warn("'" + key + "' not found in any GIR file.");
                continue;
            }
            if (classDef.isNamespaceClass && targetKeys.contains(classDef.name)) {
                // the namespace shares its name with a generated class, e.g. GObject
                classDef.name = classDef.name + "Functions";
            }
            String source = generateClassSource(classDef);
            String fileName = (classDef.isNamespaceClass ? classDef.name : classDef.cType) + ".java";
            Files.writeString(new File(packageDir, fileName).toPath(), source);
            getLogger().lifecycle("Generated: " + fileName);
        }
    }

    private void registerNamespaceAndClassStubs(Element ns) {
        String nsName = attr(ns, "name");
        String cIdPrefixes = attr(ns, "c:identifier-prefixes");
        String nsPrefix = !cIdPrefixes.isEmpty() ? cIdPrefixes.split(",")[0].trim() : nsName;
        nsTypePrefix.put(nsName, nsPrefix);

        String cSymPrefixes = attr(ns, "c:symbol-prefixes");
        String cSymPrefix = !cSymPrefixes.isEmpty()
            ? cSymPrefixes.split(",")[0].trim().toUpperCase() + "_"
            : nsPrefix.toUpperCase() + "_";
        nsSymbolPrefix.put(nsName, cSymPrefix);

        for (Element klass : childElements(ns, "class")) {
            String cType = attr(klass, "c:type");
            if (!cType.isEmpty()) {
                ClassDef def = new ClassDef();
                def.name = attr(klass, "name");
                def.namespace = nsName;
                def.cType = cType;
                def.parentGirName = attr(klass, "parent");
                def.getTypeFunc = attr(klass, "glib:get-type");
                for (Element impl : childElements(klass, "implements")) {
                    def.implementsGirNames.add(attr(impl, "name"));
                }
                classRegistry.put(cType, def);
            }
        }

        for (Element rec : childElements(ns, "record")) {
            compounds.put(nsName + "." + attr(rec, "name"), rec);
            String cType = attr(rec, "c:type");
            if (cType.isEmpty()) continue;
            ClassDef def = new ClassDef();
            def.name = attr(rec, "name");
            def.namespace = nsName;
            def.cType = cType;
            def.isRecord = true;
            def.element = rec;
            def.getTypeFunc = attr(rec, "glib:get-type");
            classRegistry.put(cType, def);
        }

        for (Element union : childElements(ns, "union")) {
            compounds.put(nsName + "." + attr(union, "name"), union);
        }

        for (Element callback : childElements(ns, "callback")) {
            callbacks.add(nsName + "." + attr(callback, "name"));
        }

        for (Element iface : childElements(ns, "interface")) {
            String cType = attr(iface, "c:type");
            if (!cType.isEmpty()) {
                ClassDef def = new ClassDef();
                def.name = attr(iface, "name");
                def.namespace = nsName;
                def.cType = cType;
                def.isInterface = true;
                def.getTypeFunc = attr(iface, "glib:get-type");
                for (Element prereq : childElements(iface, "prerequisite")) {
                    def.prerequisiteGirNames.add(attr(prereq, "name"));
                }
                classRegistry.put(cType, def);
            }
        }

        for (String tag : Arrays.asList("enumeration", "bitfield")) {
            for (Element enumNode : childElements(ns, tag)) {
                String cType = attr(enumNode, "c:type");
                if (!cType.isEmpty()) {
                    enumCTypes.add(cType);
                }
            }
        }

        for (Element alias : childElements(ns, "alias")) {
            String cType = attr(alias, "c:type");
            List<Element> typeNodes = childElements(alias, "type");
            if (!cType.isEmpty() && !typeNodes.isEmpty()) {
                aliasTargets.put(cType, new String[] { attr(typeNodes.get(0), "name"), nsName });
            }
        }

        if (includeNamespaceFunctions.contains(nsName)) {
            ClassDef def = new ClassDef();
            def.name = nsName;
            def.namespace = nsName;
            def.cType = nsName;
            def.isNamespaceClass = true;
            classRegistry.put(NS_KEY_PREFIX + nsName, def);
        }
    }

    private void resolveHierarchy() {
        for (ClassDef def : classRegistry.values()) {
            if (def.isNamespaceClass) continue;
            def.parentCType = girNameToCType(def.parentGirName, def.namespace);
            def.prerequisiteCTypes.clear();
            for (String prereq : def.prerequisiteGirNames) {
                String cType = girNameToCType(prereq, def.namespace);
                if (cType != null) def.prerequisiteCTypes.add(cType);
            }
            def.implementsCTypes.clear();
            for (String impl : def.implementsGirNames) {
                String cType = girNameToCType(impl, def.namespace);
                if (cType != null) def.implementsCTypes.add(cType);
            }
        }
    }

    /**
     * Maps a GObject class or interface that is not generated to the closest
     * generated type it can be represented as: the nearest generated ancestor
     * for classes, a generated prerequisite (or GObject) for interfaces.
     * Returns null for records and types with no generated representation.
     */
    private String nearestGeneratedType(String cType, Set<String> targetKeys, Set<String> visited) {
        if (cType == null || !visited.add(cType)) return null;
        if (targetKeys.contains(cType)) return cType;
        ClassDef def = classRegistry.get(cType);
        if (def == null || def.isRecord) return null;
        if (def.isInterface) {
            List<String> prereqs = new ArrayList<>(def.prerequisiteCTypes);
            prereqs.sort((a, b) -> Boolean.compare(isInterfaceType(a), isInterfaceType(b)));
            for (String prereq : prereqs) {
                String r = nearestGeneratedType(prereq, targetKeys, visited);
                if (r != null) return r;
            }
            return targetKeys.contains("GObject") ? "GObject" : null;
        }
        return nearestGeneratedType(def.parentCType, targetKeys, visited);
    }

    private boolean isInterfaceType(String cType) {
        ClassDef def = classRegistry.get(cType);
        return def != null && def.isInterface;
    }

    private void parseClassMethods(Element klass, String nsName, Set<String> targetKeys) {
        String cType = attr(klass, "c:type");
        if (cType.isEmpty()) return;

        ClassDef classDef = classRegistry.get(cType);
        if (classDef == null) return;

        for (Element ctor : childElements(klass, "constructor")) {
            MethodDef m = parseMethodNode(ctor, nsName, cType, true, targetKeys);
            if (m != null) classDef.constructors.add(m);
        }

        for (Element method : childElements(klass, "method")) {
            MethodDef m = parseMethodNode(method, nsName, cType, false, targetKeys);
            if (m != null) classDef.methods.add(m);
        }

        for (Element func : childElements(klass, "function")) {
            MethodDef m = parseMethodNode(func, nsName, cType, false, targetKeys);
            if (m != null) {
                m.isStatic = true;
                classDef.methods.add(m);
            }
        }
    }

    /**
     * Computes the memory layout of the records whose fields can all be
     * represented, including private, nested and callback fields, so that
     * the offsets match the C structure.
     */
    private void resolveStructLayouts() {
        for (ClassDef def : classRegistry.values()) {
            if (!def.isRecord || def.element == null) continue;
            Layout layout = compoundLayout(def.element, def.namespace, new HashSet<>());
            if (layout != null && layout.fields != null && !layout.fields.isEmpty()) {
                def.isStructRecord = true;
                def.fields = layout.fields;
            }
        }
    }

    private static final class Layout {
        final String expr;
        final long size;
        final long align;
        // the Java type of the accessors, null when the field has no accessor
        final String javaType;
        // the members of a structure or union
        List<FieldDef> fields;

        Layout(String expr, long size, long align, String javaType) {
            this.expr = expr;
            this.size = size;
            this.align = align;
            this.javaType = javaType;
        }
    }

    private static Layout scalarLayout(String javaType) {
        switch (javaType) {
            case "byte":   return new Layout("ValueLayout.JAVA_BYTE", 1, 1, javaType);
            case "short":  return new Layout("ValueLayout.JAVA_SHORT", 2, 2, javaType);
            case "int":    return new Layout("ValueLayout.JAVA_INT", 4, 4, javaType);
            case "long":   return new Layout("ValueLayout.JAVA_LONG", 8, 8, javaType);
            case "float":  return new Layout("ValueLayout.JAVA_FLOAT", 4, 4, javaType);
            case "double": return new Layout("ValueLayout.JAVA_DOUBLE", 8, 8, javaType);
            case "boolean": return scalarLayout("int");
            case "String": return scalarLayout("MemorySegment");
            case "MemorySegment": return new Layout("ValueLayout.ADDRESS", 8, 8, javaType);
            default: return null;
        }
    }

    private Layout compoundLayout(Element compound, String ns, Set<String> visiting) {
        if ("1".equals(attr(compound, "opaque")) || "1".equals(attr(compound, "disguised"))) return null;
        String key = ns + "." + attr(compound, "name");
        if (!visiting.add(key)) return null;
        try {
            List<FieldDef> fields = new ArrayList<>();
            for (Element child : childElements(compound)) {
                switch (child.getTagName()) {
                    case "field" -> {
                        FieldDef f = fieldLayout(child, ns, visiting);
                        if (f == null) return null;
                        fields.add(f);
                    }
                    case "union", "record" -> {
                        Layout nested = compoundLayout(child, ns, visiting);
                        if (nested == null) return null;
                        FieldDef f = new FieldDef();
                        f.name = attr(child, "name");
                        f.layout = nested;
                        fields.add(f);
                    }
                    default -> { }
                }
            }
            if (fields.isEmpty()) return null;
            Layout layout = "union".equals(compound.getTagName()) ? unionOf(fields) : structOf(fields);
            layout.fields = fields;
            return layout;
        } finally {
            visiting.remove(key);
        }
    }

    private FieldDef fieldLayout(Element field, String ns, Set<String> visiting) {
        if (!attr(field, "bits").isEmpty()) return null;
        Layout layout;
        List<Element> arrays = childElements(field, "array");
        List<Element> types = childElements(field, "type");
        if (!childElements(field, "callback").isEmpty()) {
            layout = scalarLayout("MemorySegment");
        } else if (!arrays.isEmpty()) {
            Element array = arrays.get(0);
            String fixed = attr(array, "fixed-size");
            if (fixed.isEmpty()) {
                layout = scalarLayout("MemorySegment");
            } else {
                List<Element> elem = childElements(array, "type");
                Layout e = elem.isEmpty() ? null : typeLayout(elem.get(0), ns, visiting);
                if (e == null) return null;
                long n = Long.parseLong(fixed);
                layout = new Layout("MemoryLayout.sequenceLayout(" + n + ", " + e.expr + ")", n * e.size, e.align, null);
            }
        } else if (!types.isEmpty()) {
            layout = typeLayout(types.get(0), ns, visiting);
        } else {
            return null;
        }
        if (layout == null) return null;
        FieldDef f = new FieldDef();
        f.name = attr(field, "name");
        f.layout = layout;
        f.type = "1".equals(attr(field, "private")) ? null : layout.javaType;
        return f;
    }

    private Layout typeLayout(Element type, String ns, Set<String> visiting) {
        String name = attr(type, "name");
        if (attr(type, "c:type").contains("*")) return scalarLayout("MemorySegment");
        if (name.isEmpty()) return null;
        if (PRIMITIVE_TYPE_MAP.containsKey(name)) return scalarLayout(PRIMITIVE_TYPE_MAP.get(name));
        String qualified = name.contains(".") ? name : ns + "." + name;
        String cType = girNameToCType(name, ns);
        for (int depth = 0; aliasTargets.containsKey(cType) && depth < 8; depth++) {
            String[] target = aliasTargets.get(cType);
            if (PRIMITIVE_TYPE_MAP.containsKey(target[0])) return scalarLayout(PRIMITIVE_TYPE_MAP.get(target[0]));
            qualified = target[0].contains(".") ? target[0] : target[1] + "." + target[0];
            cType = girNameToCType(target[0], target[1]);
        }
        if (enumCTypes.contains(cType)) return scalarLayout("int");
        if (callbacks.contains(qualified)) return scalarLayout("MemorySegment");
        Element compound = compounds.get(qualified);
        if (compound == null) return null;
        Layout nested = compoundLayout(compound, qualified.substring(0, qualified.indexOf('.')), visiting);
        return nested != null ? new Layout(nested.expr, nested.size, nested.align, null) : null;
    }

    private static String member(FieldDef f) {
        return f.name == null || f.name.isEmpty() ? f.layout.expr : f.layout.expr + ".withName(\"" + f.name + "\")";
    }

    private static List<String> structMembers(List<FieldDef> fields, long[] sizeAndAlign) {
        List<String> members = new ArrayList<>();
        long offset = 0;
        long align = 1;
        for (FieldDef f : fields) {
            if (offset % f.layout.align != 0) {
                long pad = f.layout.align - offset % f.layout.align;
                members.add("MemoryLayout.paddingLayout(" + pad + ")");
                offset += pad;
            }
            members.add(member(f));
            offset += f.layout.size;
            align = Math.max(align, f.layout.align);
        }
        if (offset % align != 0) {
            long pad = align - offset % align;
            members.add("MemoryLayout.paddingLayout(" + pad + ")");
            offset += pad;
        }
        sizeAndAlign[0] = offset;
        sizeAndAlign[1] = align;
        return members;
    }

    private static Layout structOf(List<FieldDef> fields) {
        long[] sizeAndAlign = new long[2];
        List<String> members = structMembers(fields, sizeAndAlign);
        return new Layout("MemoryLayout.structLayout(" + String.join(", ", members) + ")",
            sizeAndAlign[0], sizeAndAlign[1], null);
    }

    private static Layout unionOf(List<FieldDef> fields) {
        long size = 0;
        long align = 1;
        List<String> members = new ArrayList<>();
        for (FieldDef f : fields) {
            members.add(member(f));
            size = Math.max(size, f.layout.size);
            align = Math.max(align, f.layout.align);
        }
        size = (size + align - 1) / align * align;
        return new Layout("MemoryLayout.unionLayout(" + String.join(", ", members) + ")", size, align, null);
    }

    private MethodDef parseMethodNode(Element node, String nsName, String classCType, boolean isCtor, Set<String> targetKeys) {
        if ("0".equals(attr(node, "introspectable"))) return null;

        String cId = attr(node, "c:identifier");
        if (cId.isEmpty()) return null;

        String girName = attr(node, "name");

        String returnType;
        boolean returnTransferFull = false;
        int returnLengthIndex = -1;
        if (isCtor) {
            returnType = classCType;
        } else {
            List<Element> retValues = childElements(node, "return-value");
            if (retValues.isEmpty()) return null;
            returnType = resolveNodeType(retValues.get(0), nsName, targetKeys);
            if (returnType == null) return null;
            returnTransferFull = "full".equals(attr(retValues.get(0), "transfer-ownership"));
            if ("byte[]".equals(returnType)) {
                returnLengthIndex = Integer.parseInt(attr(childElements(retValues.get(0), "array").get(0), "length"));
            }
        }

        List<ParamDef> params = new ArrayList<>();
        boolean skip = false;

        List<Element> paramContainers = childElements(node, "parameters");
        if (!paramContainers.isEmpty()) {
            for (Element param : childElements(paramContainers.get(0), "parameter")) {
                if (skip) break;
                if (!childElements(param, "varargs").isEmpty()) {
                    skip = true;
                    break;
                }
                String pName = attr(param, "name");
                String pType = resolveNodeType(param, nsName, targetKeys);
                if (pType == null) {
                    skip = true;
                    break;
                }
                ParamDef pd = new ParamDef();
                pd.name = sanitizeJavaName(pName);
                pd.type = pType;
                String dir = attr(param, "direction");
                pd.direction = dir.isEmpty() ? "in" : dir;
                pd.transferFull = "full".equals(attr(param, "transfer-ownership"));
                if (pType.endsWith("[]") && !childElements(param, "array").isEmpty()
                        && !attr(childElements(param, "array").get(0), "length").isEmpty()) {
                    if ("in".equals(pd.direction)) {
                        pd.lengthIndex = Integer.parseInt(attr(childElements(param, "array").get(0), "length"));
                    } else {
                        pd.type = pType = "MemorySegment";
                    }
                }
                if (!"in".equals(pd.direction)) {
                    boolean callerAllocates = "1".equals(attr(param, "caller-allocates"));
                    if (callerAllocates && isWrapperType(pType)) {
                        // caller-allocated struct: the wrapper itself is the out pointer
                    } else if (pType.equals("MemorySegment") || pType.endsWith("[]")) {
                        // no typed representation, the caller passes the raw pointer
                        pd.type = "MemorySegment";
                    } else {
                        // returned through a single-element holder array
                        pd.holder = true;
                        pd.elemType = pType;
                        pd.type = pType + "[]";
                    }
                }
                params.add(pd);
            }
        }

        if (skip) return null;

        // A returned byte[] takes its length from an out parameter
        String returnLengthExpr = null;
        if (returnLengthIndex >= 0) {
            ParamDef length = returnLengthIndex < params.size() ? params.get(returnLengthIndex) : null;
            if (length != null && length.holder && isPrimitiveJavaType(length.elemType)) {
                length.implicitOut = true;
                length.implicitValue = "_" + length.name;
                returnLengthExpr = "_" + length.name + ".get(" + getValueLayout(length.elemType) + ", 0L)";
            } else {
                returnType = "MemorySegment";
            }
        }

        // The length of a byte[] parameter is passed implicitly
        for (ParamDef pd : params) {
            if (pd.lengthIndex >= 0) {
                if (pd.lengthIndex >= params.size() || !isPrimitiveJavaType(params.get(pd.lengthIndex).type)
                        || params.get(pd.lengthIndex).holder) {
                    pd.type = "byte[]".equals(pd.type) || isWrapperArray(pd.type) ? "MemorySegment" : pd.type;
                    pd.lengthIndex = -1;
                    continue;
                }
                ParamDef length = params.get(pd.lengthIndex);
                String cast = "int".equals(length.type) ? "" : "(" + length.type + ") ";
                length.implicitValue = "(" + pd.name + " != null ? " + cast + pd.name + ".length : 0)";
            }
        }

        MethodDef md = new MethodDef();
        md.javaName = isCtor ? toCtorJavaName(girName) : toCamelCase(girName);
        if (params.isEmpty() && OBJECT_METHODS.contains(md.javaName)) {
            // would override or clash with a java.lang.Object method
            md.javaName = md.javaName + "_";
        }
        md.cIdentifier = cId;
        md.returnType = returnType;
        md.params = params;
        md.isStatic = isCtor;
        md.isCtor = isCtor;
        md.returnTransferFull = returnTransferFull;
        md.returnLengthExpr = returnLengthExpr;
        md.throwsError = "1".equals(attr(node, "throws"));
        return md;
    }

    private String resolveNodeType(Element node, String nsName, Set<String> targetKeys) {
        List<Element> arrays = childElements(node, "array");
        if (!arrays.isEmpty()) {
            Element array = arrays.get(0);
            List<Element> elemTypes = childElements(array, "type");
            String elemName = elemTypes.isEmpty() ? "" : attr(elemTypes.get(0), "name");
            String zt = attr(array, "zero-terminated");
            boolean hasLength = !attr(array, "length").isEmpty();
            boolean zeroTerminated = "1".equals(zt)
                || (zt.isEmpty() && !hasLength && attr(array, "fixed-size").isEmpty());
            if (zeroTerminated && ("utf8".equals(elemName) || "filename".equals(elemName))) {
                return "String[]";
            }
            if (hasLength && ("guint8".equals(elemName) || "gint8".equals(elemName) || "gchar".equals(elemName))) {
                return "byte[]";
            }
            if (hasLength && !elemName.isEmpty() && !PRIMITIVE_TYPE_MAP.containsKey(elemName)) {
                // An array of objects, passed as an array of pointers
                String elemCType = girNameToCType(elemName, nsName);
                ClassDef elem = elemCType != null ? classRegistry.get(elemCType) : null;
                if (elem != null && !elem.isStructRecord && generatedTypes.contains(elemCType)) {
                    return elemCType + "[]";
                }
            }
            return "MemorySegment";
        }

        List<Element> typeNodes = childElements(node, "type");
        if (typeNodes.isEmpty()) return "MemorySegment";

        String typeName = attr(typeNodes.get(0), "name");
        if (typeName.isEmpty()) return "MemorySegment";

        if (PRIMITIVE_TYPE_MAP.containsKey(typeName)) {
            return PRIMITIVE_TYPE_MAP.get(typeName);
        }

        String cTypeName = girNameToCType(typeName, nsName);
        for (int depth = 0; cTypeName != null && aliasTargets.containsKey(cTypeName) && depth < 8; depth++) {
            String[] target = aliasTargets.get(cTypeName);
            if (PRIMITIVE_TYPE_MAP.containsKey(target[0])) {
                return PRIMITIVE_TYPE_MAP.get(target[0]);
            }
            cTypeName = girNameToCType(target[0], target[1]);
        }
        if (cTypeName != null) {
            if (enumCTypes.contains(cTypeName)) return "int";
            if (classRegistry.containsKey(cTypeName)) {
                return nearestGeneratedType(cTypeName, targetKeys, new HashSet<>());
            }
        }

        return "MemorySegment";
    }

    private String girNameToCType(String girName, String currentNs) {
        if (girName == null || girName.isEmpty()) return null;
        if (girName.contains(".")) {
            String[] parts = girName.split("\\.", 2);
            String ns = parts[0];
            String type = parts[1];
            String prefix = nsTypePrefix.getOrDefault(ns, ns);
            return prefix + type;
        }
        String prefix = nsTypePrefix.getOrDefault(currentNs, currentNs);
        return prefix + girName;
    }

    private String toCtorJavaName(String girName) {
        if ("new".equals(girName) || "new_".equals(girName)) return "create";
        if (girName.startsWith("create")) return toCamelCase(girName);
        String suffix = girName.replaceFirst("^new_?", "");
        if (suffix.isEmpty()) return "create";
        String camel = toCamelCase(suffix);
        if (camel.isEmpty()) return "create";
        return "create" + Character.toUpperCase(camel.charAt(0)) + (camel.length() > 1 ? camel.substring(1) : "");
    }

    public String toCamelCase(String snake) {
        if (snake == null || snake.isEmpty()) return "";
        String[] parts = snake.split("_", -1);
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < parts.length; i++) {
            String part = parts[i];
            if (part.isEmpty()) continue;
            if (i == 0) {
                sb.append(part);
            } else {
                String mapped = CAMEL_WORD_MAP.get(part.toLowerCase());
                if (mapped != null) {
                    sb.append(mapped);
                } else {
                    sb.append(Character.toUpperCase(part.charAt(0)));
                    if (part.length() > 1) sb.append(part.substring(1));
                }
            }
        }
        return sanitizeJavaName(sb.toString());
    }

    public static String sanitizeJavaName(String name) {
        return JAVA_KEYWORDS.contains(name) ? name + "_" : name;
    }

    private Set<String> resolveTargetCTypes() {
        Set<String> result = new LinkedHashSet<>();
        for (String qualified : includeClasses) {
            String[] parts = qualified.split("\\.", 2);
            if (parts.length == 2) {
                String ns = parts[0];
                String type = parts[1];
                String prefix = nsTypePrefix.getOrDefault(ns, ns);
                result.add(prefix + type);
            } else {
                result.add(qualified);
            }
        }
        for (String nsName : includeNamespaceFunctions) {
            result.add(NS_KEY_PREFIX + nsName);
        }
        return result;
    }

