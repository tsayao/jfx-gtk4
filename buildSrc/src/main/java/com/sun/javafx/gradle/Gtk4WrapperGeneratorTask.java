    private String generateInterfaceSource(ClassDef classDef) {
        List<MethodDef> allMethods = new ArrayList<>();
        allMethods.addAll(classDef.constructors);
        allMethods.addAll(classDef.methods);
        String className = classDef.cType;

        StringBuilder sb = new StringBuilder();
        sb.append(LICENSE).append(GENERATED);
        sb.append("package ").append(packageName).append(";\n\n");
        appendImports(sb, allMethods, classDef, true);

        sb.append("public interface ").append(className).append(" {\n");
        sb.append("\n    MemorySegment getPointer();\n");
        sb.append("\n    static ").append(className).append(" wrap(MemorySegment ptr) {\n");
        sb.append("        return () -> ptr;\n");
        sb.append("    }\n");
        sb.append("\n    default boolean isNull() {\n");
        sb.append("        return getPointer() == null || getPointer().address() == 0;\n");
        sb.append("    }\n");
        sb.append("\n    default <T> T cast(Function<MemorySegment, T> wrapper) {\n");
        sb.append("        return wrapper.apply(getPointer());\n");
        sb.append("    }\n");

        appendTypeMethods(sb, classDef, "static ");

        generatingInterface = true;
        try {
            for (MethodDef method : allMethods) {
                sb.append("\n").append(generateMethod(method));
            }
        } finally {
            generatingInterface = false;
        }

        appendHandles(sb, classDef, allMethods, "final class H");

        sb.append("}\n");
        return sb.toString();
    }

    private void appendImports(StringBuilder sb, List<MethodDef> allMethods, ClassDef classDef, boolean root) {
        boolean isGObject = "GObject".equals(classDef.cType);
        boolean hasTypeFunc = !classDef.getTypeFunc.isEmpty();
        boolean needsArena = isGObject || allMethods.stream().anyMatch(Gtk4WrapperGeneratorTask::isNeedsArena);
        boolean hasHandles = isGObject || hasTypeFunc || !allMethods.isEmpty();

        if (needsArena) sb.append("import java.lang.foreign.Arena;\n");
        if (hasHandles) sb.append("import java.lang.foreign.FunctionDescriptor;\n");
        sb.append("import java.lang.foreign.MemorySegment;\n");
        if (hasHandles) sb.append("import java.lang.foreign.ValueLayout;\n");
        if (root) sb.append("import java.util.function.Function;\n");
        sb.append("\n");

        Set<String> invokeImports = collectInvokeImports(allMethods);
        if (hasTypeFunc) {
            invokeImports.add("rethrow");
            invokeImports.add("isSymbolAvailable");
        }
        if (isGObject) {
            invokeImports.add("rethrow");
            invokeImports.add("readString");
        }
        List<String> sortedImports = new ArrayList<>(invokeImports);
        Collections.sort(sortedImports);
        for (String imp : sortedImports) {
            sb.append("import static ").append(packageName).append(".NativeSymbolLookup.").append(imp).append(";\n");
        }
        if (!invokeImports.isEmpty()) sb.append("\n");
    }

    private static void appendTypeMethods(StringBuilder sb, ClassDef classDef, String modifiers) {
        if (classDef.getTypeFunc.isEmpty()) return;
        sb.append("\n    ").append(modifiers).append("boolean isAvailable() {\n");
        sb.append("        return isSymbolAvailable(\"").append(classDef.getTypeFunc).append("\");\n");
        sb.append("    }\n");
        sb.append("\n    ").append(modifiers).append("long getGType() {\n");
        sb.append("        try {\n");
        sb.append("            return (long) H.GET_GTYPE.get().invokeExact();\n");
        sb.append("        } catch (Throwable _t) {\n");
        sb.append("            throw rethrow(_t);\n");
        sb.append("        }\n");
        sb.append("    }\n");
    }

    private static void appendHandles(StringBuilder sb, ClassDef classDef, List<MethodDef> allMethods, String decl) {
        if (allMethods.isEmpty() && classDef.getTypeFunc.isEmpty()) return;
        sb.append("\n    ").append(decl).append(" {\n");
        if (!classDef.getTypeFunc.isEmpty()) {
            sb.append(indent(8)).append("static final LazyHandle GET_GTYPE = new LazyHandle(\"")
              .append(classDef.getTypeFunc).append("\",\n")
              .append(indent(16)).append("FunctionDescriptor.of(ValueLayout.JAVA_LONG));\n");
        }
        for (MethodDef method : allMethods) {
            sb.append(generateHandleField(method));
        }
        sb.append("    }\n");
    }

    /**
     * Generated interfaces a class can implement without ambiguous or
     * incompatible default methods.
     */
    private List<String> acceptedInterfaces(ClassDef classDef) {
        if (classDef.acceptedInterfaces != null) return classDef.acceptedInterfaces;
        List<String> accepted = new ArrayList<>();
        classDef.acceptedInterfaces = accepted;
        Set<String> inherited = new HashSet<>();
        // signature -> return type of concrete methods, which take precedence over defaults
        Map<String, String> classSigs = new HashMap<>();
        // signatures of default methods from interfaces implemented by this class or its ancestors
        Map<String, String> defaultSigs = new HashMap<>();
        for (MethodDef m : classDef.methods) {
            if (!m.isStatic) classSigs.put(signature(m), m.returnType);
        }
        for (ClassDef parent = generatedParent(classDef); parent != null; parent = generatedParent(parent)) {
            for (MethodDef m : parent.methods) {
                if (!m.isStatic) classSigs.putIfAbsent(signature(m), m.returnType);
            }
            for (String iface : acceptedInterfaces(parent)) {
                inherited.add(iface);
                for (MethodDef m : classRegistry.get(iface).methods) {
                    if (!m.isStatic) defaultSigs.put(signature(m), m.returnType);
                }
            }
        }
        for (String ifaceCType : classDef.implementsCTypes) {
            ClassDef iface = classRegistry.get(ifaceCType);
            if (iface == null || !iface.isInterface || !generatedTypes.contains(ifaceCType)) continue;
            if (inherited.contains(ifaceCType)) continue;
            boolean compatible = true;
            for (MethodDef m : iface.methods) {
                if (m.isStatic) continue;
                String sig = signature(m);
                String classReturn = classSigs.get(sig);
                if (classReturn != null ? !classReturn.equals(m.returnType) : defaultSigs.containsKey(sig)) {
                    compatible = false;
                    break;
                }
            }
            if (compatible) {
                accepted.add(ifaceCType);
                for (MethodDef m : iface.methods) {
                    if (!m.isStatic) defaultSigs.put(signature(m), m.returnType);
                }
            }
        }
        return accepted;
    }

    /**
     * The nearest ancestor class that is generated, skipping the ones that are not.
     */
    private ClassDef generatedParent(ClassDef classDef) {
        ClassDef parent = classDef.parentCType != null ? classRegistry.get(classDef.parentCType) : null;
        while (parent != null && !generatedTypes.contains(parent.cType)) {
            parent = parent.parentCType != null ? classRegistry.get(parent.parentCType) : null;
        }
        return parent;
    }

    private static String signature(MethodDef m) {
        return m.javaName + m.params.stream()
            .filter(p -> p.implicitValue == null)
            .map(p -> p.type)
            .collect(Collectors.joining(",", "(", ")"));
    }

    private String generateStructSource(ClassDef classDef) {
        List<FieldDef> fields = classDef.fields;
        List<FieldDef> accessors = fields.stream().filter(f -> f.type != null).collect(Collectors.toList());
        // every field has an accessor, so the structure can be built from its values
        boolean plain = !accessors.isEmpty() && accessors.size() == fields.size();
        List<MethodDef> allMethods = new ArrayList<>();
        allMethods.addAll(classDef.constructors);
        allMethods.addAll(classDef.methods);
        boolean hasHandles = !allMethods.isEmpty() || !classDef.getTypeFunc.isEmpty();
        String className = classDef.cType;

        StringBuilder sb = new StringBuilder();
        sb.append(LICENSE).append(GENERATED);
        sb.append("package ").append(packageName).append(";\n\n");
        sb.append("import java.lang.foreign.Arena;\n");
        if (hasHandles) sb.append("import java.lang.foreign.FunctionDescriptor;\n");
        sb.append("import java.lang.foreign.MemoryLayout;\n");
        sb.append("import java.lang.foreign.MemorySegment;\n");
        sb.append("import java.lang.foreign.ValueLayout;\n");
        if (!accessors.isEmpty()) sb.append("import java.lang.invoke.VarHandle;\n");
        sb.append("\n");
        Set<String> invokeImports = collectInvokeImports(allMethods);
        if (!classDef.getTypeFunc.isEmpty()) {
            invokeImports.add("rethrow");
            invokeImports.add("isSymbolAvailable");
        }
        List<String> sortedImports = new ArrayList<>(invokeImports);
        Collections.sort(sortedImports);
        for (String imp : sortedImports) {
            sb.append("import static ").append(packageName).append(".NativeSymbolLookup.").append(imp).append(";\n");
        }
        if (!invokeImports.isEmpty()) sb.append("\n");

        sb.append("public final class ").append(className).append(" {\n");
        long[] sizeAndAlign = new long[2];
        List<String> members = structMembers(fields, sizeAndAlign);
        sb.append("\n    private static final MemoryLayout LAYOUT = MemoryLayout.structLayout(\n");
        for (int i = 0; i < members.size(); i++) {
            sb.append("            ").append(members.get(i)).append(i < members.size() - 1 ? "," : "").append("\n");
        }
        sb.append("    );\n\n");

        for (FieldDef f : accessors) {
            sb.append("    private static final VarHandle ").append(handleName(f))
              .append(" = LAYOUT.varHandle(MemoryLayout.PathElement.groupElement(\"").append(f.name).append("\"));\n");
        }

        sb.append("\n    private final MemorySegment seg;\n");

        String ctorParams = accessors.stream()
            .map(f -> f.type + " " + sanitizeJavaName(f.name))
            .collect(Collectors.joining(", "));

        if (plain) {
            sb.append("\n    public ").append(className).append("(").append(ctorParams).append(") {\n");
            sb.append("        this.seg = Arena.ofAuto().allocate(LAYOUT);\n");
            for (FieldDef f : accessors) {
                sb.append("        ").append(handleName(f)).append(".set(this.seg, 0L, ")
                  .append(sanitizeJavaName(f.name)).append(");\n");
            }
            sb.append("    }\n");
        }

        sb.append("\n    public ").append(className).append("(MemorySegment seg) {\n");
        sb.append("        this.seg = seg.byteSize() < LAYOUT.byteSize() ? seg.reinterpret(LAYOUT.byteSize()) : seg;\n");
        sb.append("    }\n");

        sb.append("\n    public static ").append(className).append(" create(Arena arena) {\n");
        sb.append("        return new ").append(className).append("(arena.allocate(LAYOUT));\n");
        sb.append("    }\n");

        sb.append("\n    public MemorySegment segment() {\n");
        sb.append("        return seg;\n");
        sb.append("    }\n");

        sb.append("\n    public static MemoryLayout layout() {\n");
        sb.append("        return LAYOUT;\n");
        sb.append("    }\n");

        if (plain) {
            sb.append("\n    public static MemorySegment allocate(Arena arena, ").append(ctorParams).append(") {\n");
            sb.append("        MemorySegment s = arena.allocate(LAYOUT);\n");
            for (FieldDef f : accessors) {
                sb.append("        ").append(handleName(f)).append(".set(s, 0L, ")
                  .append(sanitizeJavaName(f.name)).append(");\n");
            }
            sb.append("        return s;\n");
            sb.append("    }\n");
        }

        for (FieldDef f : accessors) {
            String jName = accessorName(f);
            sb.append("\n    public ").append(f.type).append(" ").append(jName).append("() {\n");
            sb.append("        return (").append(f.type).append(") ").append(handleName(f)).append(".get(seg, 0L);\n");
            sb.append("    }\n");
            sb.append("\n    public void ").append(jName).append("(").append(f.type).append(" value) {\n");
            sb.append("        ").append(handleName(f)).append(".set(seg, 0L, value);\n");
            sb.append("    }\n");
        }

        appendTypeMethods(sb, classDef, "public static ");

        generatingStruct = true;
        try {
            for (MethodDef method : allMethods) {
                sb.append("\n").append(generateMethod(method));
            }
        } finally {
            generatingStruct = false;
        }

        appendHandles(sb, classDef, allMethods, "private static final class H");

        sb.append("}\n");
        return sb.toString();
    }

    private static String handleName(FieldDef f) {
        String name = f.name.toUpperCase();
        return "LAYOUT".equals(name) || "H".equals(name) ? name + "_" : name;
    }

    private String accessorName(FieldDef f) {
        String name = toCamelCase(f.name);
        return OBJECT_METHODS.contains(name) ? name + "_" : name;
    }

    private String generateNamespaceFunctionSource(ClassDef classDef) {
        List<MethodDef> allMethods = classDef.methods;
        String className = classDef.name;

        boolean needsArena = allMethods.stream().anyMatch(Gtk4WrapperGeneratorTask::isNeedsArena);
        boolean hasMethods = !allMethods.isEmpty();
        Set<String> invokeImports = collectInvokeImports(allMethods);

        StringBuilder sb = new StringBuilder();
        sb.append(LICENSE).append(GENERATED);
        sb.append("package ").append(packageName).append(";\n\n");

        if (needsArena) sb.append("import java.lang.foreign.Arena;\n");
        if (hasMethods) sb.append("import java.lang.foreign.FunctionDescriptor;\n");
        sb.append("import java.lang.foreign.MemorySegment;\n");
        if (hasMethods) sb.append("import java.lang.foreign.ValueLayout;\n");
        if (hasMethods) sb.append("\n");

        List<String> sortedImports = new ArrayList<>(invokeImports);
        Collections.sort(sortedImports);
        for (String imp : sortedImports) {
            sb.append("import static ").append(packageName).append(".NativeSymbolLookup.").append(imp).append(";\n");
        }
        if (!invokeImports.isEmpty()) sb.append("\n");

        sb.append("public final class ").append(className).append(" {\n");
        sb.append("\n    private ").append(className).append("() {}\n");

        for (ConstDef c : classDef.constants) {
            sb.append("\n    public static final ").append(c.type).append(" ").append(c.name)
              .append(" = ").append(c.value).append(";\n");
        }

        for (MethodDef method : allMethods) {
            sb.append("\n").append(generateMethod(method));
        }

        if (hasMethods) {
            sb.append("\n    private static final class H {\n");
            for (MethodDef method : allMethods) {
                sb.append(generateHandleField(method));
            }
            sb.append("    }\n");
        }

        sb.append("}\n");
        return sb.toString();
    }

    private String generateMethod(MethodDef method) {
        StringBuilder sb = new StringBuilder();
        String returnType = method.returnType != null ? method.returnType : "void";
        boolean usesArena = isNeedsArena(method);
        String modifiers = generatingInterface
            ? (method.isStatic ? "static" : "default")
            : (method.isStatic ? "public static" : "public");
        String paramStr = method.params.stream()
            .filter(p -> p.implicitValue == null)
            .map(p -> p.type + " " + p.name)
            .collect(Collectors.joining(", "));

        sb.append("    ").append(modifiers).append(" ").append(returnType)
          .append(" ").append(method.javaName).append("(").append(paramStr).append(") {\n");

        if (usesArena) {
            sb.append("        try (Arena arena = Arena.ofConfined()) {\n");
            sb.append(generateMethodBody(method, indent(12)));
            sb.append("        }\n");
        } else {
            sb.append(generateMethodBody(method, indent(8)));
        }

        sb.append("    }\n");
        return sb.toString();
    }

    private static String indent(int spaces) {
        return " ".repeat(spaces);
    }

    private String generateMethodBody(MethodDef method, String ind) {
        StringBuilder sb = new StringBuilder();
        String returnType = method.returnType != null ? method.returnType : "void";
        String fieldName = handleName(method);

        List<String> post = new ArrayList<>();
        List<String> args = new ArrayList<>();
        if (!method.isStatic) args.add(generatingInterface ? "getPointer()" : generatingStruct ? "seg" : "ptr");
        for (ParamDef p : method.params) {
            if (p.implicitOut) {
                sb.append(ind).append("MemorySegment _").append(p.name).append(" = arena.allocate(")
                  .append(getValueLayout(p.elemType)).append(");\n");
                args.add("_" + p.name);
            } else if (p.holder) {
                String tmp = "_" + p.name;
                String layout = getValueLayout(p.elemType);
                String present = p.name + " != null && " + p.name + ".length > 0";
                sb.append(ind).append("MemorySegment ").append(tmp).append(" = ").append(p.name)
                  .append(" != null ? arena.allocate(").append(layout).append(") : MemorySegment.NULL;\n");
                if ("inout".equals(p.direction) && VALUE_LAYOUT_MAP.containsKey(p.elemType)
                        && !"String".equals(p.elemType) && !"MemorySegment".equals(p.elemType)) {
                    String value = "boolean".equals(p.elemType) ? "(" + p.name + "[0] ? 1 : 0)" : p.name + "[0]";
                    sb.append(ind).append("if (").append(present).append(") ").append(tmp)
                      .append(".set(").append(layout).append(", 0L, ").append(value).append(");\n");
                }
                post.add("if (" + present + ") " + p.name + "[0] = "
                    + convertNativeExpr(p.elemType, tmp + ".get(" + layout + ", 0L)", p.transferFull) + ";");
                args.add(tmp);
            } else if (p.implicitValue != null) {
                args.add(p.implicitValue);
            } else {
                args.add(convertParamExpr(p.type, p.name));
            }
        }
        if (method.throwsError) {
            // GError** out parameter; zero-initialized by the arena
            sb.append(ind).append("MemorySegment _error = arena.allocate(ValueLayout.ADDRESS);\n");
            args.add("_error");
            post.add(0, "checkError(_error);");
        }
        String call = invokeCall(fieldName, returnType, String.join(", ", args));

        if (post.isEmpty()) {
            switch (returnType) {
                case "void":
                    appendInvoke(sb, ind, call + ";");
                    return sb.toString();
                case "int":
                case "long":
                case "double":
                case "float":
                case "MemorySegment":
                    appendInvoke(sb, ind, "return " + call + ";");
                    return sb.toString();
                case "boolean":
                    appendInvoke(sb, ind, "return " + call + " != 0;");
                    return sb.toString();
                default:
                    break;
            }
        }

        if ("void".equals(returnType)) {
            appendInvoke(sb, ind, call + ";");
        } else if ("boolean".equals(returnType)) {
            sb.append(ind).append("boolean _r;\n");
            appendInvoke(sb, ind, "_r = " + call + " != 0;");
        } else if (isPrimitiveJavaType(returnType)) {
            sb.append(ind).append(returnType).append(" _r;\n");
            appendInvoke(sb, ind, "_r = " + call + ";");
        } else {
            sb.append(ind).append("MemorySegment _r;\n");
            appendInvoke(sb, ind, "_r = " + call + ";");
        }
        for (String stmt : post) {
            sb.append(ind).append(stmt).append("\n");
        }
        if (!"void".equals(returnType)) {
            String result = isPrimitiveJavaType(returnType) || "boolean".equals(returnType)
                ? "_r"
                : "byte[]".equals(returnType)
                    ? "readBytes(_r, " + method.returnLengthExpr + ", " + method.returnTransferFull + ")"
                    : convertNativeExpr(returnType, "_r", method.returnTransferFull);
            sb.append(ind).append("return ").append(result).append(";\n");
        }
        return sb.toString();
    }

    private static String invokeCall(String fieldName, String returnType, String argStr) {
        String call = "H." + fieldName + ".get().invokeExact(" + argStr + ")";
        return "void".equals(returnType) ? call : "(" + CARRIER_TYPE_MAP.get(getValueLayout(returnType)) + ") " + call;
    }

    private static void appendInvoke(StringBuilder sb, String ind, String statement) {
        sb.append(ind).append("try {\n");
        sb.append(ind).append("    ").append(statement).append("\n");
        sb.append(ind).append("} catch (Throwable _t) {\n");
        sb.append(ind).append("    throw rethrow(_t);\n");
        sb.append(ind).append("}\n");
    }

    private static boolean isPrimitiveJavaType(String type) {
        switch (type) {
            case "byte": case "short": case "int": case "long": case "float": case "double":
                return true;
            default:
                return false;
        }
    }

    /**
     * Converts a native value expression (a pointer for reference types) to the Java type.
     */
    private String convertNativeExpr(String type, String expr, boolean transferFull) {
        switch (type) {
            case "boolean":
                return expr + " != 0";
            case "byte": case "short": case "int": case "long": case "float": case "double":
            case "MemorySegment":
                return expr;
            case "String":
                return transferFull ? "readString(" + expr + ", true)" : "readString(" + expr + ")";
            case "String[]":
                return "readStringArray(" + expr + ", " + transferFull + ")";
            default:
                String seg = "_r".equals(expr) ? "_r != null ? _r : MemorySegment.NULL" : expr;
                ClassDef cd = classRegistry.get(type);
                if (cd != null && cd.isStructRecord) {
                    seg = ("_r".equals(expr) ? "(" + seg + ")" : seg) + ".reinterpret(" + type + ".layout().byteSize())";
                }
                if (cd != null && cd.isInterface) {
                    return type + ".wrap(" + seg + ")";
                }
                return "new " + type + "(" + seg + ")";
        }
    }

    private static String generateHandleField(MethodDef method) {
        String returnType = method.returnType != null ? method.returnType : "void";
        String fieldName = handleName(method);

        List<String> layouts = new ArrayList<>();
        if (!method.isStatic) layouts.add("ValueLayout.ADDRESS");
        for (ParamDef p : method.params) {
            layouts.add(getValueLayout(p.type));
        }
        if (method.throwsError) {
            layouts.add("ValueLayout.ADDRESS");
        }

        String descriptor;
        if ("void".equals(returnType)) {
            descriptor = "FunctionDescriptor.ofVoid(" + String.join(", ", layouts) + ")";
        } else {
            List<String> all = new ArrayList<>();
            all.add(getValueLayout(returnType));
            all.addAll(layouts);
            descriptor = "FunctionDescriptor.of(" + String.join(", ", all) + ")";
        }

        return indent(8) + "static final LazyHandle " + fieldName + " = new LazyHandle(\"" + method.cIdentifier + "\",\n"
             + indent(16) + descriptor + ");\n";
    }

    private static String handleName(MethodDef method) {
        String name = toScreamingSnakeCase(method.javaName);
        // GET_GTYPE holds the type function
        return "GET_GTYPE".equals(name) ? name + "_" : name;
    }

    public static String toScreamingSnakeCase(String camelCase) {
        return camelCase
            .replaceAll("([a-z])([A-Z])", "$1_$2")
            .replaceAll("([A-Z]+)([A-Z][a-z])", "$1_$2")
            .toUpperCase();
    }

    public static String getValueLayout(String type) {
        return VALUE_LAYOUT_MAP.getOrDefault(type, "ValueLayout.ADDRESS");
    }

    private String convertParamExpr(String type, String name) {
        switch (type) {
            case "boolean": return name + " ? 1 : 0";
            case "String":  return "(MemorySegment) (" + name + " != null ? arena.allocateFrom(" + name + ") : MemorySegment.NULL)";
            case "String[]": return "allocateStringArray(arena, " + name + ")";
            case "byte[]": return "allocateBytes(arena, " + name + ")";
            case "MemorySegment": return "(MemorySegment) (" + name + " != null ? " + name + " : MemorySegment.NULL)";
            default:
                if (isWrapperArray(type)) {
                    String elem = type.substring(0, type.length() - 2);
                    return "allocatePointers(arena, " + name + ", " + elem + "::getPointer)";
                }
                if (isWrapperType(type)) {
                    ClassDef cd = classRegistry.get(type);
                    String accessor = (cd != null && cd.isStructRecord) ? "segment()" : "getPointer()";
                    return "(MemorySegment) (" + name + " != null ? " + name + "." + accessor + " : MemorySegment.NULL)";
                }
                return name;
        }
    }

    public static String toJavaLiteral(String jType, String value) {
        switch (jType) {
            case "int":
                try {
                    Integer.parseInt(value);
                    return value;
                } catch (NumberFormatException ignored) {}
                try {
                    return String.format("0x%08X", Integer.parseUnsignedInt(value));
                } catch (NumberFormatException ignored) {
                    return null;
                }
            case "long":
                try {
                    Long.parseLong(value);
                    return value + "L";
                } catch (NumberFormatException ignored) {
                    try {
                        long l = Long.parseUnsignedLong(value);
                        return l + "L";
                    } catch (NumberFormatException ignored2) {
                        return null;
                    }
                }
            case "double":
                try {
                    Double.parseDouble(value);
                    return value + (value.contains(".") || value.contains("e") ? "" : ".0");
                } catch (NumberFormatException ignored) {
                    return null;
                }
            case "float":
                try {
                    Float.parseFloat(value);
                    return value;
                } catch (NumberFormatException ignored) {
                    return null;
                }
            case "String":
                if (value == null) return null;
                return "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"") + "\"";
            default:
                return null;
        }
    }

    public static boolean isNeedsArena(MethodDef method) {
        return method.throwsError
            || method.params.stream().anyMatch(p -> p.holder || p.implicitOut || "String".equals(p.type)
                || "String[]".equals(p.type) || "byte[]".equals(p.type) || isWrapperArray(p.type));
    }

    public boolean isPointerJavaType(String type) {
        return "String".equals(type) || "MemorySegment".equals(type) || isWrapperType(type);
    }

    private static boolean isWrapperArray(String type) {
        return type.endsWith("[]") && !"String[]".equals(type) && !"byte[]".equals(type)
            && !isPrimitiveJavaType(type.substring(0, type.length() - 2))
            && !"boolean".equals(type.substring(0, type.length() - 2));
    }

    public static boolean isWrapperType(String type) {
        return type != null && !type.equals("void") && !type.endsWith("[]") && !VALUE_LAYOUT_MAP.containsKey(type);
    }

    public static Set<String> collectInvokeImports(List<MethodDef> methods) {
        Set<String> result = new LinkedHashSet<>();
        for (MethodDef m : methods) {
            String rt = m.returnType != null ? m.returnType : "void";
            result.add("rethrow");
            if ("String".equals(rt)) result.add("readString");
            if ("String[]".equals(rt)) result.add("readStringArray");
            if (m.throwsError) result.add("checkError");
            if ("byte[]".equals(rt)) result.add("readBytes");
            for (ParamDef p : m.params) {
                if ("String[]".equals(p.type)) result.add("allocateStringArray");
                if ("byte[]".equals(p.type)) result.add("allocateBytes");
                if (isWrapperArray(p.type) && !p.holder) result.add("allocatePointers");
                if (p.holder && "String".equals(p.elemType)) result.add("readString");
            }
        }
        return result;
    }

    private static List<Element> childElements(Element parent) {
        List<Element> result = new ArrayList<>();
        NodeList children = parent.getChildNodes();
        for (int i = 0; i < children.getLength(); i++) {
            if (children.item(i) instanceof Element e) {
                result.add(e);
            }
        }
        return result;
    }

    private static List<Element> childElements(Element parent, String tagName) {
        List<Element> result = new ArrayList<>();
        if (parent == null) return result;
        NodeList children = parent.getChildNodes();
        for (int i = 0; i < children.getLength(); i++) {
            Node child = children.item(i);
            if (child.getNodeType() == Node.ELEMENT_NODE && tagName.equals(((Element) child).getTagName())) {
                result.add((Element) child);
            }
        }
        return result;
    }

    private static String attr(Element e, String attrName) {
        if (e == null) return "";
        String v = e.getAttribute(attrName);
        return v != null ? v : "";
    }

