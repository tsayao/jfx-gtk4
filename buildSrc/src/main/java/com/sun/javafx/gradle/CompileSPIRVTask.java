package com.sun.javafx.gradle;

import org.gradle.api.DefaultTask;
import org.gradle.api.GradleException;
import org.gradle.api.tasks.InputDirectory;
import org.gradle.api.tasks.OutputDirectory;
import org.gradle.api.tasks.PathSensitive;
import org.gradle.api.tasks.PathSensitivity;
import org.gradle.api.tasks.TaskAction;

import java.io.File;
import java.io.IOException;
import java.lang.foreign.Arena;
import java.lang.foreign.FunctionDescriptor;
import java.lang.foreign.Linker;
import java.lang.foreign.MemorySegment;
import java.lang.foreign.SymbolLookup;
import java.lang.foreign.ValueLayout;
import java.lang.invoke.MethodHandle;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.stream.Stream;

/**
 * Compiles Vulkan GLSL shaders ({@code .vert} and {@code .frag}) to SPIR-V
 * ({@code .spv}), keeping the directory structure. Other files, such as the
 * shader layouts generated by JSLC, are copied unchanged.
 * <p>
 * Shaders are compiled with libshaderc when it is available, or else with the
 * {@code glslc} tool.
 */
public class CompileSPIRVTask extends DefaultTask {

    private File source;
    private File output;

    @InputDirectory
    @PathSensitive(PathSensitivity.RELATIVE)
    public File getSource() {
        return source;
    }

    public void setSource(File source) {
        this.source = source;
    }

    @OutputDirectory
    public File getOutput() {
        return output;
    }

    public void setOutput(File output) {
        this.output = output;
    }

    @TaskAction
    public void compile() throws Exception {
        if (!source.isDirectory()) {
            return;
        }
        List<Path> files;
        try (Stream<Path> walk = Files.walk(source.toPath())) {
            files = walk.filter(Files::isRegularFile).toList();
        }
        try (Compiler compiler = Compiler.create()) {
            for (Path file : files) {
                Path relative = source.toPath().relativize(file);
                String name = file.getFileName().toString();
                Path target = output.toPath().resolve(relative);
                Files.createDirectories(target.getParent());
                if (name.endsWith(".vert") || name.endsWith(".frag")) {
                    Path spv = target.resolveSibling(name + ".spv");
                    if (!Files.exists(spv) || Files.getLastModifiedTime(spv).compareTo(Files.getLastModifiedTime(file)) < 0) {
                        Files.write(spv, compiler.compile(file, name.endsWith(".vert")));
                    }
                } else {
                    Files.copy(file, target, java.nio.file.StandardCopyOption.REPLACE_EXISTING);
                }
            }
        }
    }

    /**
     * Returns whether libshaderc or the glslc tool is available.
     */
    public static boolean isCompilerAvailable() {
        try (Compiler shaderc = Shaderc.load()) {
            if (shaderc != null) {
                return true;
            }
        }
        String path = System.getenv("PATH");
        if (path != null) {
            for (String dir : path.split(File.pathSeparator)) {
                if (Files.isExecutable(Path.of(dir, "glslc"))) {
                    return true;
                }
            }
        }
        return false;
    }

    private interface Compiler extends AutoCloseable {
        byte[] compile(Path file, boolean vertex) throws Exception;

        @Override
        void close();

        static Compiler create() {
            Compiler shaderc = Shaderc.load();
            return shaderc != null ? shaderc : new Glslc();
        }
    }

    /**
     * Compiles with the glslc command line tool.
     */
    private static final class Glslc implements Compiler {
        @Override
        public byte[] compile(Path file, boolean vertex) throws Exception {
            Path out = Files.createTempFile("jfx", ".spv");
            try {
                Process p = new ProcessBuilder("glslc", "--target-env=vulkan1.3", "-O",
                        "-o", out.toString(), file.toString())
                        .redirectErrorStream(true).start();
                String log = new String(p.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
                if (p.waitFor() != 0) {
                    throw new GradleException("glslc failed for " + file + ":\n" + log);
                }
                return Files.readAllBytes(out);
            } catch (IOException e) {
                throw new GradleException("Cannot compile Vulkan shaders: neither libshaderc nor glslc is available", e);
            } finally {
                Files.deleteIfExists(out);
            }
        }

        @Override
        public void close() {
        }
    }

    /**
     * Compiles with libshaderc, through the foreign function API.
     */
    private static final class Shaderc implements Compiler {
        private static final int SHADERC_VERTEX_SHADER = 0;
        private static final int SHADERC_FRAGMENT_SHADER = 1;
        private static final int SHADERC_TARGET_ENV_VULKAN = 0;
        private static final int SHADERC_ENV_VERSION_VULKAN_1_3 = (1 << 22) | (3 << 12);
        private static final int SHADERC_OPTIMIZATION_LEVEL_PERFORMANCE = 2;

        private final Arena arena = Arena.ofConfined();
        private final MethodHandle compileIntoSpv;
        private final MethodHandle getStatus;
        private final MethodHandle getLength;
        private final MethodHandle getBytes;
        private final MethodHandle getError;
        private final MethodHandle releaseResult;
        private final MethodHandle releaseCompiler;
        private final MethodHandle releaseOptions;
        private final MemorySegment compiler;
        private final MemorySegment options;

        private Shaderc(SymbolLookup lib) throws Throwable {
            Linker linker = Linker.nativeLinker();
            ValueLayout ptr = ValueLayout.ADDRESS;
            ValueLayout i32 = ValueLayout.JAVA_INT;
            MethodHandle compilerInit = linker.downcallHandle(lib.find("shaderc_compiler_initialize").orElseThrow(),
                    FunctionDescriptor.of(ptr));
            MethodHandle optionsInit = linker.downcallHandle(lib.find("shaderc_compile_options_initialize").orElseThrow(),
                    FunctionDescriptor.of(ptr));
            MethodHandle setTargetEnv = linker.downcallHandle(lib.find("shaderc_compile_options_set_target_env").orElseThrow(),
                    FunctionDescriptor.ofVoid(ptr, i32, i32));
            MethodHandle setOptimization = linker.downcallHandle(
                    lib.find("shaderc_compile_options_set_optimization_level").orElseThrow(),
                    FunctionDescriptor.ofVoid(ptr, i32));
            compileIntoSpv = linker.downcallHandle(lib.find("shaderc_compile_into_spv").orElseThrow(),
                    FunctionDescriptor.of(ptr, ptr, ptr, ValueLayout.JAVA_LONG, i32, ptr, ptr, ptr));
            getStatus = linker.downcallHandle(lib.find("shaderc_result_get_compilation_status").orElseThrow(),
                    FunctionDescriptor.of(i32, ptr));
            getLength = linker.downcallHandle(lib.find("shaderc_result_get_length").orElseThrow(),
                    FunctionDescriptor.of(ValueLayout.JAVA_LONG, ptr));
            getBytes = linker.downcallHandle(lib.find("shaderc_result_get_bytes").orElseThrow(),
                    FunctionDescriptor.of(ptr, ptr));
            getError = linker.downcallHandle(lib.find("shaderc_result_get_error_message").orElseThrow(),
                    FunctionDescriptor.of(ptr, ptr));
            releaseResult = linker.downcallHandle(lib.find("shaderc_result_release").orElseThrow(),
                    FunctionDescriptor.ofVoid(ptr));
            releaseCompiler = linker.downcallHandle(lib.find("shaderc_compiler_release").orElseThrow(),
                    FunctionDescriptor.ofVoid(ptr));
            releaseOptions = linker.downcallHandle(lib.find("shaderc_compile_options_release").orElseThrow(),
                    FunctionDescriptor.ofVoid(ptr));

            compiler = (MemorySegment) compilerInit.invokeExact();
            options = (MemorySegment) optionsInit.invokeExact();
            setTargetEnv.invokeExact(options, SHADERC_TARGET_ENV_VULKAN, SHADERC_ENV_VERSION_VULKAN_1_3);
            setOptimization.invokeExact(options, SHADERC_OPTIMIZATION_LEVEL_PERFORMANCE);
        }

        static Shaderc load() {
            for (String name : new String[] {"libshaderc_shared.so.1", "libshaderc_shared.so", "libshaderc.so.1"}) {
                try {
                    return new Shaderc(SymbolLookup.libraryLookup(name, Arena.global()));
                } catch (Throwable ignored) {
                }
            }
            return null;
        }

        @Override
        public byte[] compile(Path file, boolean vertex) throws Exception {
            String code = Files.readString(file);
            try (Arena call = Arena.ofConfined()) {
                MemorySegment src = call.allocateFrom(code);
                MemorySegment result;
                try {
                    result = (MemorySegment) compileIntoSpv.invokeExact(compiler, src, src.byteSize() - 1,
                            vertex ? SHADERC_VERTEX_SHADER : SHADERC_FRAGMENT_SHADER,
                            call.allocateFrom(file.getFileName().toString()), call.allocateFrom("main"), options);
                } catch (Throwable t) {
                    throw new GradleException("shaderc failed for " + file, t);
                }
                try {
                    int status = (int) getStatus.invokeExact(result);
                    if (status != 0) {
                        MemorySegment msg = ((MemorySegment) getError.invokeExact(result)).reinterpret(Long.MAX_VALUE);
                        throw new GradleException("Cannot compile " + file + ":\n" + msg.getString(0));
                    }
                    long length = (long) getLength.invokeExact(result);
                    MemorySegment bytes = ((MemorySegment) getBytes.invokeExact(result)).reinterpret(length);
                    return bytes.toArray(ValueLayout.JAVA_BYTE);
                } catch (GradleException e) {
                    throw e;
                } catch (Throwable t) {
                    throw new GradleException("shaderc failed for " + file, t);
                } finally {
                    try {
                        releaseResult.invokeExact(result);
                    } catch (Throwable ignored) {
                    }
                }
            }
        }

        @Override
        public void close() {
            try {
                releaseOptions.invokeExact(options);
                releaseCompiler.invokeExact(compiler);
            } catch (Throwable ignored) {
            }
            arena.close();
        }
    }
}
